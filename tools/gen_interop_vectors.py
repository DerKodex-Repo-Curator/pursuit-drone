#!/usr/bin/env python3
"""Capture real Python-generated packets as C test vectors.

The firmware and the vision stack each have their own tests, and
gen_protocol_header.py asserts their struct sizes agree. None of that proves
they interoperate: field ORDER can differ while sizes match, endianness can be
right in one direction and wrong in the other, and a CRC computed over a
different byte range on each side is self-consistent within each language and
rejects everything across the link.

Every one of those bugs passes both suites and fails on the first flight.

So this writes actual bytes from vision/pursuit/protocol.py into a header the
firmware tests parse with the code the aircraft will run.

    python3 tools/gen_interop_vectors.py

Re-run it whenever the protocol changes, then `pio test -e native`.
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "vision"))

from pursuit.protocol import (FLAG_ALT_HOLD, FLAG_ARMED,        # noqa: E402
                              FLAG_FAILSAFE, FLAG_LOCKED, Command)

OUT = os.path.join(ROOT, "firmware", "test", "test_interop",
                   "interop_vectors.h")

# One per interesting state the aircraft can be commanded into, plus a
# deliberately out-of-range one to prove the firmware clamps rather than
# trusting the sender.
CASES = [
    ("armed_hover", Command(seq=1, t_ms=100, alt_sp=1.20,
                            flags=FLAG_ARMED | FLAG_ALT_HOLD)),
    ("armed_locked", Command(seq=2, t_ms=133, roll=1.5, pitch=-2.25,
                             yaw_rate=45.0, alt_sp=1.40,
                             flags=FLAG_ARMED | FLAG_ALT_HOLD | FLAG_LOCKED)),
    ("failsafe", Command(seq=3, t_ms=166, alt_sp=1.40,
                         flags=FLAG_ARMED | FLAG_ALT_HOLD | FLAG_FAILSAFE)),
    ("disarmed", Command(seq=4, t_ms=199, alt_sp=1.40, flags=FLAG_ALT_HOLD)),
    ("manual", Command(seq=5, t_ms=232, roll=10.0, pitch=-14.0,
                       yaw_rate=-120.0, alt_sp=0.65, flags=FLAG_ARMED)),
    ("extreme", Command(seq=6, t_ms=265, roll=900.0, pitch=-900.0,
                        yaw_rate=9000.0, alt_sp=50.0,
                        flags=FLAG_ARMED | FLAG_ALT_HOLD)),
]


def main() -> int:
    lines = [
        "/* GENERATED by tools/gen_interop_vectors.py — do not edit.",
        " *",
        " * Real command packets produced by the Python vision stack",
        " * (vision/pursuit/protocol.py), captured as bytes so the firmware",
        " * tests can prove the two implementations actually interoperate —",
        " * not merely that their struct sizes agree.",
        " */",
        "#ifndef PURSUIT_INTEROP_VECTORS_H",
        "#define PURSUIT_INTEROP_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        "struct InteropVector {",
        "    const char *name;",
        "    const uint8_t bytes[30];",
        "    float roll, pitch, yaw_rate, alt_sp;",
        "    uint32_t seq;",
        "    uint8_t flags;",
        "};",
        "",
        "static const InteropVector INTEROP_VECTORS[] = {",
    ]
    for name, cmd in CASES:
        raw = cmd.pack()
        body = ", ".join(f"0x{b:02X}" for b in raw)
        lines += [
            f'    {{ "{name}",',
            f"      {{ {body} }},",
            f"      {cmd.roll}f, {cmd.pitch}f, {cmd.yaw_rate}f, "
            f"{cmd.alt_sp}f,",
            f"      {cmd.seq}u, 0x{cmd.flags:02X} }},",
        ]
    lines += [
        "};",
        "",
        f"static const int INTEROP_VECTOR_COUNT = {len(CASES)};",
        "",
        "#endif",
    ]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"wrote {len(CASES)} vectors -> "
          f"{os.path.relpath(OUT, ROOT)}")
    for name, cmd in CASES:
        print(f"  {name:14} {cmd.pack().hex()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
