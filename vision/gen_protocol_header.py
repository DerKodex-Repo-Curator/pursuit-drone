#!/usr/bin/env python3
"""Emit the firmware's copy of the wire format from `pursuit/protocol.py`.

Two implementations of one packet layout is how you get a drone that flies
sideways: someone adds a field on the Python side, the C struct still parses,
and every value after the insertion point is silently shifted. So the C header
is generated, never hand-edited, and this script asserts that the field table
below adds up to exactly the size `struct.calcsize` reports for the Python
format string. Change one side without the other and the build fails here
rather than in the air.

    python gen_protocol_header.py            # write firmware/include/pursuit_link.h
    python gen_protocol_header.py --check    # verify only, non-zero if stale
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from pursuit import protocol as P  # noqa: E402

ROOT = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.normpath(
    os.path.join(ROOT, "..", "firmware", "include", "pursuit_link.h"))

# (C type, name, bytes, comment) — order is the wire order.
CMD_FIELDS = [
    ("uint16_t", "magic",    2, "PURSUIT_CMD_MAGIC"),
    ("uint8_t",  "version",  1, "PURSUIT_PROTOCOL_VERSION"),
    ("uint8_t",  "flags",    1, "PURSUIT_FLAG_*"),
    ("uint32_t", "seq",      4, "monotonic, wraps"),
    ("uint32_t", "t_ms",     4, "sender clock, for latency"),
    ("float",    "roll",     4, "deg, + = right wing down"),
    ("float",    "pitch",    4, "deg, + = nose down / forward"),
    ("float",    "yaw_rate", 4, "deg/s, + = clockwise from above"),
    ("float",    "alt_sp",   4, "m AGL if ALT_HOLD, else throttle 0..1"),
    ("uint16_t", "crc",      2, "CRC-16/CCITT-FALSE over bytes [0, size-2)"),
]

TELEM_FIELDS = [
    ("uint16_t", "magic",    2, "PURSUIT_TELEM_MAGIC"),
    ("uint8_t",  "version",  1, "PURSUIT_PROTOCOL_VERSION"),
    ("uint8_t",  "state",    1, "PURSUIT_STATE_*"),
    ("uint32_t", "seq",      4, ""),
    ("uint32_t", "t_ms",     4, ""),
    ("float",    "vbat",     4, "V, from the D2 divider"),
    ("float",    "alt",      4, "m AGL, from the VL53L1X"),
    ("float",    "roll",     4, "deg"),
    ("float",    "pitch",    4, "deg"),
    ("float",    "yaw",      4, "deg"),
    ("uint16_t", "loop_hz",  2, "measured control-loop rate"),
    ("uint16_t", "crc",      2, ""),
]


def _struct(name: str, fields) -> str:
    width = max(len(t) for t, _, _, _ in fields)
    lines = [f"typedef struct __attribute__((packed)) {{"]
    for ctype, fname, _, comment in fields:
        pad = " " * (width - len(ctype))
        tail = f"  /* {comment} */" if comment else ""
        lines.append(f"    {ctype}{pad} {fname};{tail}")
    lines.append(f"}} {name};")
    return "\n".join(lines)


def render() -> str:
    cmd_size = sum(n for _, _, n, _ in CMD_FIELDS)
    telem_size = sum(n for _, _, n, _ in TELEM_FIELDS)
    assert cmd_size == P.CMD_SIZE, \
        f"command field table is {cmd_size}B, protocol.py says {P.CMD_SIZE}B"
    assert telem_size == P.TELEM_SIZE, \
        f"telemetry field table is {telem_size}B, protocol.py says {P.TELEM_SIZE}B"

    return f"""/* pursuit_link.h — PURSUIT-1 laptop <-> flight-controller wire format.
 *
 * GENERATED by vision/gen_protocol_header.py from vision/pursuit/protocol.py.
 * Do not edit by hand: regenerate, or the two ends of the link will disagree
 * about where the fields are and every value past the change will be garbage.
 *
 * Little-endian, packed. The ESP32 is little-endian, so the receive path can
 * memcpy straight into the struct with no byte swapping.
 *
 * Receiver contract, in order:
 *   1. length == sizeof(struct)      3. version == PURSUIT_PROTOCOL_VERSION
 *   2. magic  == expected magic      4. crc matches
 *   5. seq is newer than the last accepted one   (drop stale/reordered)
 *   6. every float is finite                     (isfinite(), not a range test)
 * A packet failing any check is DISCARDED, not clamped. A command you cannot
 * trust is worse than no command: the watchdog below handles absence safely.
 *
 * WATCHDOG: if no valid command arrives for PURSUIT_LINK_TIMEOUT_MS, the
 * firmware must level the aircraft and descend. Do not hold the last command —
 * a stale yaw rate flies it into a wall at constant speed.
 */
#ifndef PURSUIT_LINK_H
#define PURSUIT_LINK_H

#include <stdint.h>

/* This header is included from both C and C++ translation units — the ESP32
 * firmware is C++, and clang accepts C11's _Static_assert in C++ as an
 * extension while GCC does not. Getting this wrong compiles cleanly on a Mac
 * and fails only on the toolchain that actually builds the flight firmware. */
#ifdef __cplusplus
#  define PURSUIT_STATIC_ASSERT(cond, msg) static_assert(cond, msg)
#else
#  define PURSUIT_STATIC_ASSERT(cond, msg) _Static_assert(cond, msg)
#endif

#define PURSUIT_PROTOCOL_VERSION  {P.PROTOCOL_VERSION}u
#define PURSUIT_CMD_MAGIC         0x{P.CMD_MAGIC:04X}u
#define PURSUIT_TELEM_MAGIC       0x{P.TELEM_MAGIC:04X}u
#define PURSUIT_CMD_PORT          {14550}u
#define PURSUIT_TELEM_PORT        {14551}u
#define PURSUIT_LINK_TIMEOUT_MS   {400}u

/* command flags */
#define PURSUIT_FLAG_ARMED     (1u << 0)  /* operator is holding arm      */
#define PURSUIT_FLAG_LOCKED    (1u << 1)  /* vision has a confirmed target*/
#define PURSUIT_FLAG_ALT_HOLD  (1u << 2)  /* alt_sp is metres, not throttle*/
#define PURSUIT_FLAG_FAILSAFE  (1u << 3)  /* vision gave up — hold level   */

/* vehicle state, reported in telemetry */
#define PURSUIT_STATE_BOOT      {P.STATE_BOOT}u
#define PURSUIT_STATE_IDLE      {P.STATE_IDLE}u
#define PURSUIT_STATE_ARMED     {P.STATE_ARMED}u
#define PURSUIT_STATE_FLYING    {P.STATE_FLYING}u
#define PURSUIT_STATE_FAILSAFE  {P.STATE_FAILSAFE}u
#define PURSUIT_STATE_LANDING   {P.STATE_LANDING}u

{_struct("pursuit_cmd_t", CMD_FIELDS)}

{_struct("pursuit_telem_t", TELEM_FIELDS)}

PURSUIT_STATIC_ASSERT(sizeof(pursuit_cmd_t)   == {P.CMD_SIZE},
                      "pursuit_cmd_t must be {P.CMD_SIZE} bytes");
PURSUIT_STATIC_ASSERT(sizeof(pursuit_telem_t) == {P.TELEM_SIZE},
                      "pursuit_telem_t must be {P.TELEM_SIZE} bytes");

/* CRC-16/CCITT-FALSE: poly 0x1021, init 0xFFFF, no reflection, no xorout. */
static inline uint16_t pursuit_crc16(const uint8_t *data, uint32_t len)
{{
    uint16_t crc = 0xFFFFu;
    for (uint32_t i = 0; i < len; ++i) {{
        crc ^= (uint16_t)data[i] << 8;
        for (uint8_t b = 0; b < 8; ++b)
            crc = (crc & 0x8000u) ? (uint16_t)((crc << 1) ^ 0x1021u)
                                  : (uint16_t)(crc << 1);
    }}
    return crc;
}}

/* Returns 1 if the buffer is a well-formed command. Does NOT check seq —
 * the caller owns that, because only it knows the last accepted value. */
static inline int pursuit_cmd_valid(const uint8_t *buf, uint32_t len)
{{
    if (len != sizeof(pursuit_cmd_t)) return 0;
    pursuit_cmd_t c;
    __builtin_memcpy(&c, buf, sizeof(c));
    if (c.magic != PURSUIT_CMD_MAGIC) return 0;
    if (c.version != PURSUIT_PROTOCOL_VERSION) return 0;
    if (c.crc != pursuit_crc16(buf, (uint32_t)sizeof(c) - 2u)) return 0;
    if (!__builtin_isfinite(c.roll)  || !__builtin_isfinite(c.pitch)) return 0;
    if (!__builtin_isfinite(c.yaw_rate) || !__builtin_isfinite(c.alt_sp)) return 0;
    return 1;
}}

/* Unsigned-wrap-safe "is a STRICTLY newer than b".
 *
 * Strict is the point. The sender transmits each command several times so a
 * burst of WiFi loss cannot gap the link; a non-strict comparison would treat
 * every copy as fresh and apply the same setpoint repeatedly. */
static inline int pursuit_seq_newer(uint32_t a, uint32_t b)
{{
    uint32_t delta = (uint32_t)(a - b);
    return delta != 0u && delta < 0x80000000u;
}}

#endif /* PURSUIT_LINK_H */
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true",
                    help="verify the file on disk is current")
    args = ap.parse_args()

    text = render()

    if args.check:
        if not os.path.exists(args.out):
            print(f"MISSING {args.out}")
            return 1
        current = open(args.out).read()
        if current != text:
            print(f"STALE   {args.out} — rerun gen_protocol_header.py")
            return 1
        print(f"ok      {args.out} is current")
        return 0

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as fh:
        fh.write(text)
    print(f"wrote {args.out}  "
          f"(cmd {P.CMD_SIZE}B, telem {P.TELEM_SIZE}B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
